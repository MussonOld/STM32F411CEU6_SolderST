/**
 * @file eeprom_hw.h
 * @brief Приватные константы используемой микросхемы EEPROM (адрес на шине,
 *        геометрия, тайминги)
 *
 * ТЕКУЩИЙ ЧИП: 24C04 (4 Кбит = 512 байт). При смене на 24C02/24C08/24C16
 * или FM24C64 (FRAM) — поменять значения ниже и логику в .c-файле реализации;
 * само имя этого файла менять не нужно.
 *
 * Не инклюдится ничем, кроме файла реализации драйвера. Верхний слой
 * работает только через eeprom.h.
 */

#ifndef EEPROM_HW_H
#define EEPROM_HW_H

/* Базовый 7-битный адрес устройства 0b1010_A2A1_P0, сдвинутый под HAL
 * (8-битный формат с битом R/W). A1..A2 в этой схеме подтянуты к GND
 * (единственная микросхема на шине) => базовый адрес 0xA0.
 *
 * ВАЖНО: у 24C04 (в отличие от 24C02) слово адреса ячейки — 8 бит, но
 * ёмкость 512 байт требует 9 бит адреса. Девятый (старший) бит адреса —
 * это бит P0, который передаётся не в самом адресном байте, а в бите 1
 * адресного байта устройства (там, где у 24C02 был бы вывод A0).
 * Итоговый адрес устройства собирается динамически в eeprom_24c04.c:
 *   device_addr = EEPROM_HW_I2C_ADDR_BASE | (block << EEPROM_HW_BLOCK_BIT_POS)
 * где block = (addr >> 8) & 0x01. Если разводка A1/A2 изменится — поправить
 * здесь. */
#define EEPROM_HW_I2C_ADDR_BASE    (0xA0)

/* Позиция бита выбора блока (P0) внутри адресного байта устройства */
#define EEPROM_HW_BLOCK_BIT_POS    (1U)

/* Ёмкость: 4 Кбит = 512 байт */
#define EEPROM_HW_SIZE_BYTES       (512U)

/* Размер страницы записи 24C04 — 16 байт (datasheet Microchip 24LC04B /
 * Atmel AT24C04) */
#define EEPROM_HW_PAGE_SIZE        (16U)

/* Время внутреннего цикла записи страницы (datasheet: tWR, максимум обычно
 * 5 мс). Берём с запасом под опрос готовности. */
#define EEPROM_HW_WRITE_TIMEOUT_MS  (20U)

/* Число попыток HAL_I2C_IsDeviceReady за один вызов опроса готовности */
#define EEPROM_HW_READY_TRIALS      (1U)

#endif /* EEPROM_HW_H */
